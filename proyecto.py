def graficar_barras(columna, orden, titulo, color='#4C72B0'):
    conteo = data[columna].value_counts(dropna=False)
    conteo = conteo.reindex(orden).fillna(0)

    plt.figure(figsize=(7,4))
    barras = plt.bar(conteo.index.astype(str), conteo.values, color=color)
    plt.title(titulo, fontsize=13)
    plt.ylabel('Número de personas')
    plt.xticks(rotation=30, ha='right')

    plt.ylim(0, conteo.values.max() * 1.15)

    for barra in barras:
        altura = barra.get_height()
        plt.text(barra.get_x() + barra.get_width()/2, altura + 6, int(altura),
                  ha='center', fontsize=8)

    plt.tight_layout()
    plt.show()

