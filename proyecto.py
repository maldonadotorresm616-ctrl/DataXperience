def graficar_cruce_proporciones(col_x, orden_x, col_y, orden_y, titulo, xlabel, leyenda):
    tabla = pd.crosstab(data[col_x], data[col_y])
    tabla = tabla.reindex(index=orden_x, columns=orden_y)
    tabla_prop = tabla.div(tabla.sum(axis=1), axis=0)

    fig, ax = plt.subplots(figsize=(9,5))
    tabla_prop.plot(kind='bar', stacked=True, color=colores, ax=ax)

    for contenedor in ax.containers:
        etiquetas = [f'{valor*100:.1f}%' if valor > 0.02 else '' for valor in contenedor.datavalues]
        ax.bar_label(contenedor, labels=etiquetas, label_type='center', fontsize=8, color='white')

    plt.title(titulo)
    plt.xlabel(xlabel)
    plt.ylabel('Proporción')
    plt.xticks(rotation=30, ha='right')
    plt.legend(title=leyenda, bbox_to_anchor=(1.02, 1), loc='upper left')
    plt.tight_layout()
    plt.show()

    return tabla

